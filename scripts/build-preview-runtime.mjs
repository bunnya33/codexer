import { readFile, writeFile } from 'node:fs/promises';
import { transform } from 'esbuild';
import { resolve } from 'node:path';

const source=resolve('packages/client-shared/src/preview-bridge.ts');
const destination=resolve('packages/client-shared/src/preview-runtime-source.ts');
const compiled=await transform(await readFile(source,'utf8'),{loader:'ts',target:'es2022',charset:'utf8',legalComments:'none'});
const script=compiled.code.replace(/^export /,'');
const output='// Generated by scripts/build-preview-runtime.mjs; Hermes requires literal script source.\nexport const PREVIEW_RUNTIME_SOURCE = '+JSON.stringify(script)+';\n';
if(process.argv.includes('--check')){
  if(await readFile(destination,'utf8')!==output) throw new Error('Preview runtime is stale: run node scripts/build-preview-runtime.mjs');
  process.stdout.write('Preview runtime source is current.\n');
}else{
  await writeFile(destination,output);
  process.stdout.write('Preview runtime source generated.\n');
}
